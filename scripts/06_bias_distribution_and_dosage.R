# Sample-name patterns used to identify experimental conditions.
pattern_UP <- "_U"
pattern_P  <- "_P"

# Histogram display range and bin width.
histogram_min <- -10
histogram_max <- 10
histogram_binwidth <- 0.25


# ==============================================================================
# 4. Define plot colors
# ==============================================================================

bias_colors <- c(
  "No bias" = "grey85",
  "C bias"  = "#9BCD9B",
