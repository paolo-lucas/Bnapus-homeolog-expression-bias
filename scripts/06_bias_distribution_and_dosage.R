# ==============================================================================
# SCRIPT: Homoeolog expression bias distribution and global transcriptomic dosage
#
# Description:
# This script generates:
#   1. Histograms showing the distribution of homoeolog expression bias for
#      Unprimed and Primed conditions.
#   2. Dot plots showing the global transcriptomic dosage of the BnA and BnC
#      subgenomes in each biological replicate.
#   3. A summary table containing the number and percentage of homoeologous
#      gene pairs classified as A bias, C bias, or No bias.
#
# Inputs:
#   - Bias_Analysis_<Lineage>.xlsx files generated by
#     05_homeolog_expression_bias.R.
#   - The original TPM-normalized expression matrix.
#
# IMPORTANT:
# The histograms use the LFC_UP and LFC_P values calculated by
# 05_homeolog_expression_bias.R. They are not recalculated here, ensuring that
# the plotted values are identical to those used for bias classification.
#
# Global transcriptomic dosage is calculated from the complete TPM matrix,
# independently of the RBH-filtered gene-pair dataset. For each biological
# sample, total TPM is summed separately for genes belonging to the BnA and BnC
# subgenomes, and each subgenome is expressed as a proportion of the combined
# BnA + BnC expression.
#
# TPM sample columns must begin with the corresponding lineage prefix.
# Sample names must also contain the condition patterns defined below:
#   "_U" for Unprimed samples
#   "_P" for Primed samples
# ==============================================================================


